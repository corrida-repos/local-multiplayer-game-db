const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync(require('node:path').join(__dirname,'../website/app.js'),'utf8');
const cut=(a,b)=>{const s=src.indexOf(a),e=src.indexOf(b,s);assert.ok(s>=0&&e>s,'code not found: '+a);return src.slice(s,e)};
const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const safeUrl=s=>{try{const u=new URL(s);return u.protocol==='https:'?u.href:''}catch{return ''}};
const context={URL,Date,esc,safeUrl,entryKey:g=>`${g.platform}:${g.id}`,enrichment:{},psplus:{}};vm.createContext(context);
vm.runInContext(cut('let media=null','function refreshGallery(').replace('let media=null,mediaLoading=null;','var media=null,mediaLoading=null;'),context);
vm.runInContext(cut('function trailerHeading','function trailerMarkup'),context);
vm.runInContext(cut('function plusInfo','function updatePlusControl'),context);
assert.ok(src.includes('${trailerMarkup(g)}${galleryMarkup(g)}'),'detail view must render the gallery');
const g={id:'1',platform:'PS5',title:'Example'};
assert.match(vm.runInContext('galleryMarkup',context)(g),/gallery-section/,'placeholder before media loads');
vm.runInContext(`media={'PS5:1':{screenshots:['https://image.api.playstation.com/a.jpg','javascript:alert(1)','https://shared.akamai.steamstatic.com/x/ss.1920x1080.jpg']}}`,context);
const html=vm.runInContext('galleryMarkup',context)(g);
assert.equal((html.match(/class="gallery-shot"/g)||[]).length,2,'unsafe URLs are dropped');
assert.match(html,/a\.jpg\?w=640/);assert.match(html,/ss\.600x338\.jpg/);
assert.equal(vm.runInContext('galleryMarkup',context)({id:'2',platform:'PS5',title:'None'}),'','no empty section once loaded');
const h=vm.runInContext('trailerHeading',context);
assert.equal(h({kind:'trailer',source:'https://www.playstation.com/x'}),'Trailer oficial');
assert.equal(h({kind:'gameplay',source:'YouTube search'}),'Trailer de gameplay');
assert.equal(h({kind:'video',source:'YouTube search'}),'Vídeo do jogo');
const old=new Date(Date.now()-60*3600e3).toISOString(),fresh=new Date().toISOString();
vm.runInContext(`enrichment={'PS5:1':{psplus:{region:'PT',in_catalog:false,checked:'${old}'}}};psplus={'PS5:1':{region:'PT',in_catalog:true,checked:'${fresh}'}}`,context);
assert.equal(vm.runInContext('plusIncluded',context)(g),true,'newest PS Plus check wins and 60h is still fresh');
console.log('media view ok');
